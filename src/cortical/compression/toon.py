"""Lossless pure-Python stdlib TOON (Token-Oriented Object Notation) encoder & decoder."""

from __future__ import annotations

import json
import re
from typing import Any


_SCALAR_TYPES = (type(None), bool, int, float, str)
_UNIFORM_HEADER_RE = re.compile(r"^([A-Za-z0-9_.\-]*)\[(\d+)\]\{([^}]+)\}:$")


def _needs_quotes(s: str, for_table: bool = False) -> bool:
    if s == "" or s != s.strip():
        return True
    if s in {"true", "false", "null", "[]", "{}"}:
        return True
    if re.fullmatch(r"-?(?:0|[1-9]\d*)(?:\.\d+)?(?:[eE][+-]?\d+)?", s):
        return True
    specials = {',', '"', '\\', '\n', '\r', '\t'} if for_table else {'"', '\\', '\n', '\r', '\t', ':'}
    return any(ch in specials for ch in s) or s.startswith(("[", "{"))


def _format_scalar(v: Any, for_table: bool = False) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    s = str(v)
    return json.dumps(s, ensure_ascii=False) if _needs_quotes(s, for_table=for_table) else s


def _parse_scalar(raw: str) -> Any:
    t = raw.strip()
    if t == "null":
        return None
    if t == "true":
        return True
    if t == "false":
        return False
    if t.startswith('"'):
        return json.loads(t)
    if re.fullmatch(r"-?(?:0|[1-9]\d*)", t):
        return int(t)
    if re.fullmatch(r"-?(?:0|[1-9]\d*)(?:\.\d+)?(?:[eE][+-]?\d+)?", t):
        return float(t)
    if t.startswith(("[", "{")):
        return json.loads(t)
    return t


def _split_csv_row(line: str) -> list[str]:
    cells: list[str] = []
    cur: list[str] = []
    in_quotes = False
    escaped = False
    for ch in line:
        if escaped:
            cur.append(ch)
            escaped = False
            continue
        if in_quotes:
            cur.append(ch)
            if ch == "\\":
                escaped = True
            elif ch == '"':
                in_quotes = False
            continue
        if ch == '"':
            in_quotes = True
            cur.append(ch)
        elif ch == ",":
            cells.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    cells.append("".join(cur))
    return cells


def _is_uniform_scalar_table(val: Any) -> bool:
    if not isinstance(val, list) or len(val) < 2:
        return False
    if not all(isinstance(row, dict) and row for row in val):
        return False
    keys = list(val[0].keys())
    if not all(re.fullmatch(r"[A-Za-z0-9_.\-]+", str(k)) and "," not in str(k) for k in keys):
        return False
    for row in val:
        if list(row.keys()) != keys:
            return False
        if not all(isinstance(v, _SCALAR_TYPES) for v in row.values()):
            return False
    return True


def _encode_value(val: Any, name: str = "", indent: int = 0) -> list[str]:
    pad = "  " * indent
    if _is_uniform_scalar_table(val):
        keys = list(val[0].keys())
        hdr = f"{pad}{name}[{len(val)}]{{{','.join(keys)}}}:"
        lines = [hdr]
        row_pad = "  " * (indent + 1)
        for row in val:
            lines.append(row_pad + ",".join(_format_scalar(row[k], for_table=True) for k in keys))
        return lines

    if isinstance(val, dict):
        if not val:
            return [f"{pad}{name}: {{}}" if name else "{}"]
        lines: list[str] = []
        if name:
            lines.append(f"{pad}{name}:")
            child_indent = indent + 1
        else:
            child_indent = indent
        cpad = "  " * child_indent
        for k, v in val.items():
            ks = str(k) if re.fullmatch(r"[A-Za-z0-9_.\-]+", str(k)) else json.dumps(str(k), ensure_ascii=False)
            if _is_uniform_scalar_table(v) or (isinstance(v, dict) and v):
                lines.extend(_encode_value(v, name=ks, indent=child_indent))
            elif isinstance(v, (dict, list)):
                lines.append(f"{cpad}{ks}: {json.dumps(v, ensure_ascii=False, separators=(',', ':'))}")
            else:
                lines.append(f"{cpad}{ks}: {_format_scalar(v, for_table=False)}")
        return lines

    if isinstance(val, list):
        dumped = json.dumps(val, ensure_ascii=False, separators=(",", ":"))
        return [f"{pad}{name}: {dumped}" if name else dumped]

    formatted = _format_scalar(val, for_table=False)
    return [f"{pad}{name}: {formatted}" if name else formatted]


def encode_toon(data: Any) -> str:
    """Deterministically serializes Python JSON-compatible objects into lossless TOON format."""
    return "\n".join(_encode_value(data))


def decode_toon(text: str) -> Any:
    """Losslessly parses TOON output generated by `encode_toon` back into Python data structures."""
    raw_lines = [ln.rstrip("\r\n") for ln in text.splitlines() if ln.strip()]
    if not raw_lines:
        return {}
    if len(raw_lines) == 1 and raw_lines[0].strip() in {"{}", "[]"}:
        return json.loads(raw_lines[0].strip())

    def _parse_block(idx: int, min_indent: int) -> tuple[Any, int]:
        first = raw_lines[idx]
        cur_indent = len(first) - len(first.lstrip(" "))
        stripped = first.strip()

        m_root_tbl = _UNIFORM_HEADER_RE.match(stripped)
        if m_root_tbl and m_root_tbl.group(1) == "":
            count = int(m_root_tbl.group(2))
            cols = m_root_tbl.group(3).split(",")
            idx += 1
            rows: list[dict[str, Any]] = []
            for _ in range(count):
                cells = _split_csv_row(raw_lines[idx].strip())
                rows.append({col: _parse_scalar(cells[ci]) for ci, col in enumerate(cols)})
                idx += 1
            return (rows, idx)

        if ":" not in stripped:
            return (_parse_scalar(stripped), idx + 1)

        out: dict[str, Any] = {}
        while idx < len(raw_lines):
            ln = raw_lines[idx]
            ind = len(ln) - len(ln.lstrip(" "))
            if ind < min_indent:
                break
            st = ln.strip()
            m_tbl = _UNIFORM_HEADER_RE.match(st)
            if m_tbl:
                key_name = m_tbl.group(1)
                count = int(m_tbl.group(2))
                cols = m_tbl.group(3).split(",")
                idx += 1
                rows = []
                for _ in range(count):
                    cells = _split_csv_row(raw_lines[idx].strip())
                    rows.append({col: _parse_scalar(cells[ci]) for ci, col in enumerate(cols)})
                    idx += 1
                out[key_name] = rows
                continue

            # key: value or nested key:
            if st.startswith('"'):
                # split closing quote before colon
                m_q = re.match(r'^("(?:\\.|[^"\\])*")\s*:\s*(.*)$', st)
                key = json.loads(m_q.group(1)) if m_q else st
                rest = m_q.group(2) if m_q else ""
            else:
                k_part, _, rest = st.partition(":")
                key = k_part.strip()
                rest = rest.strip()

            if rest == "":
                idx += 1
                if idx < len(raw_lines):
                    nxt_ind = len(raw_lines[idx]) - len(raw_lines[idx].lstrip(" "))
                    if nxt_ind > ind:
                        child, idx = _parse_block(idx, nxt_ind)
                        out[key] = child
                        continue
                out[key] = {}
            else:
                out[key] = _parse_scalar(rest)
                idx += 1
        return (out, idx)

    first_ind = len(raw_lines[0]) - len(raw_lines[0].lstrip(" "))
    parsed, _ = _parse_block(0, first_ind)
    return parsed
